#!/usr/bin/env python3
"""Compile standalone TikZ figures to SVG files and load them in a Verso visuals module.

Usage: scripts/tikz-to-verso-svg.py OUT.lean FIGURE.tex...

Each FIGURE.tex is a standalone LaTeX document whose first lines name the Verso
directive and its accessible description:

    % directive: erasureCodeSchemeFigure
    % aria-label: Erasure code: the sender encodes ...

The script compiles each figure with pdflatex, converts the PDF with pdf2svg, prefixes
the SVG ids with the file name so that several figures can share a page, and rounds
coordinates to two decimals. It writes each SVG to `figures/FIGURE.svg` next to OUT.lean,
and OUT.lean with one directive per figure, which reads its SVG with `include_str`.
Lake does not track files read by `include_str`, so the docstring of each figure records
a hash of its SVG: regenerating a changed figure changes OUT.lean, which Lake rebuilds.
Requires pdflatex and pdf2svg on the PATH.
"""
from __future__ import annotations

import hashlib
import html
import pathlib
import re
import subprocess
import sys
import tempfile

HEADER = '''/-
Copyright (c) 2026 Beneficial AI Foundation. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
-/

import VersoManual
import VersoManual.Diagrams

/-! # {title}

SVG figures generated by `scripts/tikz-to-verso-svg.py` from the TikZ sources
{sources}, stored in `figures/` next to this file.
Edit the sources and regenerate the figures and this file instead of editing them.
-/

open Verso Genre Manual Doc Elab
open Lean
'''

FIGURE = '''
/-- SVG of `{source}` (SHA-256 prefix `{digest}`). -/
private def {name}Svg : String := include_str "figures/{stem}.svg"

/-- Embed `{source}` with Verso's SVG renderer. -/
@[directive]
def {name} : DirectiveExpanderOf Unit
  | (), _ =>
    ``(Block.other
      (Block.diagram $(quote {name}Svg) "100%" "\\\\textwidth" false) #[])
'''


def header_field(tex: str, field: str) -> str:
    match = re.search(rf"^% {field}: (.+)$", tex, re.M)
    if not match:
        raise SystemExit(f"missing '% {field}:' line")
    return match.group(1).strip()


def compile_svg(tex_path: pathlib.Path) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
             f"-output-directory={tmp}", tex_path.name],
            cwd=tex_path.parent, check=True, stdout=subprocess.DEVNULL)
        pdf = pathlib.Path(tmp) / f"{tex_path.stem}.pdf"
        svg = pathlib.Path(tmp) / f"{tex_path.stem}.svg"
        subprocess.run(["pdf2svg", str(pdf), str(svg)], check=True)
        return svg.read_text()


def clean_svg(svg: str, prefix: str, label: str) -> str:
    svg = re.sub(r"<\?xml[^>]*\?>\s*", "", svg)
    root = re.search(r"<svg\b[^>]*>", svg)
    width = float(re.search(r'width="([\d.]+)pt"', root.group(0)).group(1))
    view_box = re.search(r'viewBox="([^"]+)"', root.group(0)).group(1)
    new_root = (
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'viewBox="{view_box}" style="display:block;width:100%;max-width:{round(2 * width)}px;'
        f'height:auto;margin:0 auto" role="img" aria-label="{html.escape(label)}">')
    svg = svg[:root.start()] + new_root + svg[root.end():]
    svg = re.sub(r'id="([^"]+)"', lambda m: f'id="{prefix}-{m.group(1)}"', svg)
    svg = re.sub(r'href="#([^"]+)"', lambda m: f'href="#{prefix}-{m.group(1)}"', svg)
    svg = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#{prefix}-{m.group(1)})", svg)
    svg = re.sub(r"-?\d+\.\d{3,}",
                 lambda m: f"{float(m.group(0)):.2f}".rstrip("0").rstrip("."), svg)
    return re.sub(r"\n\s+", "\n", svg).strip() + "\n"


def module_title(stem: str) -> str:
    """`ErasureCodeFigures` -> `Erasure code figures`, `SCKAFigures` -> `SCKA figures`."""
    words = re.findall(r"[A-Z]+(?![a-z])|[A-Z][a-z]*|[a-z]+|\d+", stem)
    return " ".join([words[0]] + [w if w.isupper() else w.lower() for w in words[1:]])


def write_outputs(out: pathlib.Path, source_dirs: list[str],
                  figures: list[tuple[str, str, str]]) -> None:
    """Write each `(source, directive, svg)` to `figures/` next to `out`, and `out`."""
    figure_dir = out.parent / "figures"
    figure_dir.mkdir(exist_ok=True)
    parts = [HEADER.format(title=module_title(out.stem),
                           sources="in " + ", ".join(f"`{d}`" for d in source_dirs))]
    for source, name, svg in figures:
        stem = pathlib.Path(source).stem
        (figure_dir / f"{stem}.svg").write_text(svg)
        digest = hashlib.sha256(svg.encode()).hexdigest()[:16]
        parts.append(FIGURE.format(source=source, name=name, stem=stem, digest=digest))
    out.write_text("".join(parts))


def main() -> None:
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    out = pathlib.Path(sys.argv[1])
    sources = [pathlib.Path(p) for p in sys.argv[2:]]
    figures = []
    for tex_path in sources:
        tex = tex_path.read_text()
        name = header_field(tex, "directive")
        label = header_field(tex, "aria-label")
        figures.append((tex_path.name, name, clean_svg(compile_svg(tex_path), tex_path.stem, label)))
    write_outputs(out, sorted({p.parent.as_posix() for p in sources}), figures)
    print(f"wrote {out} and {len(sources)} SVG files in {out.parent / 'figures'}")


if __name__ == "__main__":
    main()
